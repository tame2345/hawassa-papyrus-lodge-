export type LangDict = Partial<Record<AppLang, string>> & { en: string };

export function normalizeAppLang(lang?: string | null): AppLang {
  if (lang && (SUPPORTED_LANG_CODES as string[]).includes(lang)) {
    return lang as AppLang;
  }
  return 'am';
}

export function resolveText(lang: string, dict: LangDict, params?: Record<string, string | number>): string {
  const code = normalizeAppLang(lang);
  let text = dict[code] || dict.en;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function getCurrencyLabel(lang: string): string {
  const code = normalizeAppLang(lang);
  if (code === 'am' || code === 'ti') return 'ብር';
  if (code === 'ar') return 'بر';
  return 'ETB';
}

